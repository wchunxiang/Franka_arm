#!/usr/bin/env python3
"""
execute_magnet_path.py  –  Auto-execute a magnet trajectory on the Franka FR3

This ROS node loads a trajectory file (5×N or 6×N) generated by
generate_magnet_path.py and drives the arm through all waypoints.

Execution strategy:
  1. PRIMARY: MoveIt compute_cartesian_path() — plans the entire trajectory
     (or chunks) as a smooth Cartesian path in one shot.
  2. FALLBACK: If Cartesian planning fails (fraction < threshold), falls back
     to point-by-point MoveIt plan() + execute() for the remaining waypoints.

Modes:
  --mode auto     :  Executes all waypoints automatically with a configurable
                     delay between points (default).
  --mode manual   :  Waits for the user to press Enter before each step.
  --mode joystick :  Waits for joystick B button (same as original tracking).

Usage:
  rosrun <pkg> execute_magnet_path.py --config config.json --trajectory magnet_path.txt --mode auto

Dependencies:
  Same as franka_magnet_controller.py  +  the trajectory .txt files.

Author: (generated with assistance from Claude)
"""

